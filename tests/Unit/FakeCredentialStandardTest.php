<?php
declare(strict_types=1);

namespace FreeFormCertificate\Tests\Unit;

use FreeFormCertificate\Tests\Support\FakeCredentialLiterals;
use FreeFormCertificate\Tests\Support\FakeCredentials;
use PHPUnit\Framework\TestCase;

/**
 * Every credential literal in tests, seed scripts and workflows is fake (#2637).
 *
 * WHAT IT IS FOR
 *
 * A secret sweep found no real credential in the repository, but it had to
 * read every hit to say so, because `s3cret`, `open-sesame`, `admin`/`admin`
 * and `wordpress` look the same as a password pasted by mistake. This guard
 * makes the answer mechanical: a literal given to a credential-like key must
 * start with `fake-`, so a real one fails CI instead of waiting for a sweep.
 * The named values live in `FakeCredentials` (PHP) and
 * `tests/js/fake-credentials.js` (JS).
 *
 * WHAT IT DOES NOT JUDGE
 *
 * A value of three characters or fewer is the test's subject (a password too
 * short to accept, a `'0'` restriction flag). A value read from a variable, a
 * constant or a secret is not a literal. A record's link tokens
 * (`magic_token`, `confirmation_token`) are generated by the plugin and are
 * not credentials. And, like every guard here, it sees presence, never truth:
 * a real password that happens to start with `fake-` passes.
 *
 * @covers \FreeFormCertificate\Tests\Support\FakeCredentialLiterals
 * @covers \FreeFormCertificate\Tests\Support\FakeCredentials
 */
class FakeCredentialStandardTest extends TestCase {

	public function test_every_credential_literal_is_fake(): void {
		$this->assertSame(
			array(),
			FakeCredentialLiterals::findings(),
			"These credential literals are not marked fake. Use a value from tests/Support/FakeCredentials.php\n"
			. "(or tests/js/fake-credentials.js), or prefix the literal with 'fake-' when the value itself is under test."
		);
	}

	public function test_every_named_value_is_fake(): void {
		$values = FakeCredentials::all();
		$this->assertNotEmpty( $values );
		foreach ( $values as $name => $value ) {
			$this->assertStringStartsWith( FakeCredentialLiterals::PREFIX, $value, $name . ' is not marked fake.' );
		}
		$this->assertSame( array_values( array_unique( $values ) ), array_values( $values ), 'Two names share one value, so a test cannot tell them apart.' );
	}

	public function test_the_js_module_carries_the_same_values(): void {
		$source = (string) file_get_contents( FakeCredentialLiterals::root() . '/tests/js/fake-credentials.js' );
		preg_match_all( "/^\\s*([A-Z_]+):\\s*'([^']*)',?$/m", $source, $matches );
		$js = array_combine( $matches[1], $matches[2] );

		$this->assertSame( FakeCredentials::all(), $js, 'tests/js/fake-credentials.js and FakeCredentials disagree.' );
	}

	public function test_the_workflow_and_the_seed_use_the_named_values(): void {
		$root     = FakeCredentialLiterals::root();
		$workflow = FakeCredentialLiterals::literals( (string) file_get_contents( $root . '/.github/workflows/ci.yml' ), 'yml' );
		$values   = array_column( $workflow, 'value', 'key' );

		$this->assertSame( FakeCredentials::DB_PASSWORD, $values['MARIADB_ROOT_PASSWORD'] ?? null );
		$this->assertSame( FakeCredentials::DB_PASSWORD, $values['dbpass'] ?? null, 'WordPress connects with the password the database was started with.' );
		$this->assertSame( FakeCredentials::ADMIN_PASSWORD, $values['admin_password'] ?? null );

		$seed = FakeCredentialLiterals::literals( (string) file_get_contents( $root . '/.github/scripts/screenshots/seed.php' ), 'php' );
		$this->assertContains( FakeCredentials::DEMO_PASSWORD, array_column( $seed, 'value' ) );
	}

	/**
	 * The shapes the scan must see, in each language it reads.
	 *
	 * @dataProvider caught_shapes
	 */
	public function test_the_scan_catches_each_shape( string $source, string $extension, string $value ): void {
		$found = array_column( FakeCredentialLiterals::literals( $source, $extension ), 'value' );
		$this->assertContains( $value, $found );
		$this->assertFalse( FakeCredentialLiterals::is_acceptable( $value ) );
	}

	/**
	 * @return array<string, array{string, string, string}>
	 */
	public static function caught_shapes(): array {
		return array(
			'php array key'      => array( "<?php \$a = array( 'smtp_pass' => 'hunter22' );", 'php', 'hunter22' ),
			'php define'         => array( "<?php define( 'AUTH_KEY', 'realish-key' );", 'php', 'realish-key' ),
			'php nested key'     => array( "<?php \$a = array( 'new_password' => 'Sup3rSecret' );", 'php', 'Sup3rSecret' ),
			'js object key'      => array( "const a = { password: 'hunter22' };", 'js', 'hunter22' ),
			'js define snippet'  => array( "expect(x).toBe(\"define( 'FFC_ENCRYPTION_KEY', 'realkey9' );\");", 'js', 'realkey9' ),
			'yaml key'           => array( "        env:\n          MARIADB_ROOT_PASSWORD: rootpw1\n", 'yml', 'rootpw1' ),
			'command-line flag'  => array( "wp config create --dbpass=rootpw1 --dbhost=x\n", 'yml', 'rootpw1' ),
			'api key'            => array( "<?php \$a = array( 'ipinfo_api_key' => 'abc123def' );", 'php', 'abc123def' ),
		);
	}

	/**
	 * The shapes the scan must leave alone.
	 *
	 * @dataProvider ignored_shapes
	 */
	public function test_the_scan_leaves_non_credentials_alone( string $source, string $extension ): void {
		$flagged = array_filter(
			FakeCredentialLiterals::literals( $source, $extension ),
			static fn( array $hit ): bool => ! FakeCredentialLiterals::is_acceptable( $hit['value'] )
		);
		$this->assertSame( array(), array_values( $flagged ) );
	}

	/**
	 * @return array<string, array{string, string}>
	 */
	public static function ignored_shapes(): array {
		return array(
			'link token'          => array( "<?php \$a = array( 'magic_token' => 'abc123abc123' );", 'php' ),
			'reset url key'       => array( "<?php \$a = array( 'password_reset_url' => 'https://x.test' );", 'php' ),
			'ui label'            => array( "const s = { changePassword: 'Change Password' };", 'js' ),
			'constant name map'   => array( "const d = { FFC_ENCRYPTION_KEY: 'purpose line' };", 'js' ),
			'boolean flag'        => array( "const r = { password: true };", 'js' ),
			'subject flag'        => array( "<?php \$a = array( 'password' => '0' );", 'php' ),
			'secret reference'    => array( "        env:\n          DB_PASSWORD: \${{ secrets.DB_PASSWORD }}\n", 'yml' ),
			'comment'             => array( "<?php // 'smtp_pass' => 'hunter22'\n", 'php' ),
			'fake value'          => array( "<?php \$a = array( 'smtp_pass' => 'fake-anything' );", 'php' ),
		);
	}

	/**
	 * The scan reads the files it claims to: a second traversal, by glob, finds
	 * the same list.
	 */
	public function test_the_scan_reads_every_file_in_scope(): void {
		$root     = FakeCredentialLiterals::root();
		$recount  = array();
		$walk     = static function ( string $dir, array $extensions ) use ( &$walk, &$recount, $root ): void {
			foreach ( (array) glob( $dir . '/*' ) as $path ) {
				if ( is_dir( $path ) ) {
					$walk( $path, $extensions );
				} elseif ( in_array( strtolower( pathinfo( $path, PATHINFO_EXTENSION ) ), $extensions, true ) && ! str_contains( $path, '/fixtures/' ) ) {
					$recount[] = substr( $path, strlen( $root ) + 1 );
				}
			}
		};
		foreach ( FakeCredentialLiterals::SCOPE as $dir => $extensions ) {
			$walk( $root . '/' . $dir, $extensions );
		}
		sort( $recount );

		$files = FakeCredentialLiterals::files();
		$this->assertSame( $recount, $files );
		$this->assertContains( 'tests/bootstrap.php', $files );
		$this->assertContains( '.github/workflows/ci.yml', $files );
		$this->assertContains( 'tests/js/fake-credentials.js', $files );
	}
}
